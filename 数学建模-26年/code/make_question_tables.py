"""Regenerate the three question-specific Q2 tables from frozen source files.

Reads selection_v2.json, experiments_v2.json and prepared_v2_q2.npz.
Writes only tables/question2_*.tex. No simulation, policy change or data writes.
Run: py -3.12 code/make_question_tables.py
"""
from __future__ import annotations
import hashlib
import json
from pathlib import Path
import numpy as np

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data"
TABLES = ROOT / "tables"
NAMES = {
    "last_week": "前一周", "weekday_2": "同星期2日",
    "weekday_4": "同星期4日", "mean_3": "最近3日",
    "mean_7": "最近7日", "mean_14": "最近14日",
}


def read_json(name):
    return json.loads((DATA / name).read_text(encoding="utf-8"))


def table_text(caption, labels, spec, headers, rows, note, sources):
    lines = ["% Generated by code/make_question_tables.py; do not edit values."]
    for source in sources:
        path = DATA / source
        digest = hashlib.sha256(path.read_bytes()).hexdigest()
        lines.append(f"% Source: data/{source}; SHA256={digest}")
    lines += [
        r"\begin{table}[htbp]\centering\small",
        r"\caption{" + caption + "}",
        *[r"\label{" + label + "}" for label in labels],
        r"\begin{tabularx}{\linewidth}{" + spec + r"}\toprule",
        " & ".join(headers) + r"\\\midrule",
        *[" & ".join(str(x) for x in row) + r"\\" for row in rows],
        r"\bottomrule\end{tabularx}",
        r"\par\smallskip\parbox{\linewidth}{\footnotesize " + note + "}",
        r"\end{table}",
    ]
    return "\n".join(lines) + "\n"


def forecast_validation(selection):
    entry = selection["cases"]["q2"]
    records = entry["validation_candidates"]
    load_trials = [r for r in records if r["stage"] == "forecast_load_model"]
    if not load_trials:
        raise ValueError("Q2 selection is missing load-model calibration trials.")
    common_config = load_trials[0]["config"]
    if any(r["config"] != common_config for r in load_trials):
        raise ValueError("Load-model validation did not use a common controller configuration.")
    if common_config["controller"] != "lp":
        raise ValueError("This paper table describes forecast calibration with the inner LP.")
    rows = []
    for record in load_trials:
        forecasts = record["forecasts"]
        rows.append([
            "负载比较", NAMES[forecasts["load_model"]],
            NAMES[forecasts["pv_model"]], f'{record["summary"]["total_cost"]:.2f}',
        ])

    # calibrate_v2 caches identical configurations. The 7-day PV trial may
    # therefore appear only as a load-model trial, with no separate PV-stage
    # record. Reconstruct the PV comparison by matching the full configuration.
    chosen_load = entry["forecasts"]["load_model"]
    matched_pv = {}
    for record in records:
        if (record["config"] == common_config
                and record["forecasts"]["load_model"] == chosen_load):
            name = record["forecasts"]["pv_model"]
            previous = matched_pv.get(name)
            if previous is not None:
                assert record["summary"]["total_cost"] == previous["summary"]["total_cost"]
            matched_pv[name] = record
    if not matched_pv:
        raise ValueError("Q2 selection is missing the selected load model's PV trials.")
    for pv_name in sorted(matched_pv, key=lambda name: int(name.split("_")[-1])):
        record = matched_pv[pv_name]
        rows.append([
            "光伏比较", NAMES[chosen_load], NAMES[pv_name],
            f'{record["summary"]["total_cost"]:.2f}',
        ])
    return table_text(
        "问题二预测器的一月实际费用验证",
        ["tab:q2-forecast-validation"], "LLLR",
        ["比较步骤", "负载预测", "光伏预测", "实际费用/元"], rows,
        "此处固定内层LP及其余设置；相同配置复用同一次计算。随后单独比较执行器。费用不含终端目标项。",
        ["selection_v2.json"],
    )


def prediction_errors(selection):
    periods = [selection["calibration_period"], selection["evaluation_period"]]
    with np.load(DATA / "prepared_v2_q2.npz", allow_pickle=False) as prepared:
        dates = prepared["dates"]
        rows = []
        for label, actual, forecast in (
            ("负载", "load", "forecast_load"),
            ("光伏", "pv", "forecast_pv_history"),
        ):
            row = [label]
            for first, last in periods:
                mask = (dates >= first) & (dates <= last)
                if not np.any(mask):
                    raise ValueError(f"Empty prediction-error period: {first} to {last}")
                error = prepared[actual][mask] - prepared[forecast][mask]
                row.extend([
                    f"{np.mean(np.abs(error)):.2f}",
                    f"{np.sqrt(np.mean(error**2)):.2f}",
                ])
            rows.append(row)
    return table_text(
        "问题二已选预测器的误差，单位为kW",
        ["tab:q2-prediction-errors"], "LRRRR",
        ["变量", "一月MAE", "一月RMSE", "评价期MAE", "评价期RMSE"], rows,
        "一月指标取1月15--31日，评价期取2--12月。类型按一月结算费用选择，表中误差不用于重选。",
        ["selection_v2.json", "prepared_v2_q2.npz"],
    )


def scenario_comparison(experiments):
    rows, summaries = [], []
    for count in (28, 12):
        record = experiments["experiments"][f"q2_scenarios_{count}"]
        if record["status"] != "complete":
            raise ValueError(f"The {count}-scenario experiment is not complete.")
        summary = record["summary"]
        summaries.append(summary)
        rows.append([
            str(count), f'{summary["total_cost"] / 1e4:.2f}',
            f'{summary["emergency_energy"]:.2f}',
            f'{summary["daily_cost_cvar95"]:.2f}',
            f'{summary["mean_seconds_per_day"]:.4f}',
        ])
    if summaries[0]["days"] != summaries[1]["days"]:
        raise ValueError("Scenario comparison uses different evaluation lengths.")
    if abs(summaries[0]["initial_energy"] - summaries[1]["initial_energy"]) > 1e-6:
        raise ValueError("Scenario comparison uses different opening inventories.")
    days = summaries[0]["days"]
    first_final = summaries[0]["final_energy"]
    second_final = summaries[1]["final_energy"]
    note = (
        f"相同{days}天、预测、执行器及期初库存；末库存分别为{first_final:.2f}"
        f"和{second_final:.2f} kWh。时间包含预测、求解和执行，在本机并行条件下仅反映工程量级。"
    )
    return table_text(
        "问题二完整场景与压缩场景的同条件比较",
        ["tab:v2_scenarios", "tab:v2_solve_times"], "LRRRR",
        ["场景数", "总费/万元", "紧急量/kWh", "日费CVaR95/元", "秒/日"],
        rows, note, ["experiments_v2.json"],
    )


def main():
    selection = read_json("selection_v2.json")
    experiments = read_json("experiments_v2.json")
    if not selection.get("frozen"):
        raise ValueError("January selection has not been frozen.")
    outputs = {
        "question2_forecast_validation.tex": forecast_validation(selection),
        "question2_prediction_errors.tex": prediction_errors(selection),
        "question2_scenario_comparison.tex": scenario_comparison(experiments),
    }
    TABLES.mkdir(exist_ok=True)
    for name, content in outputs.items():
        (TABLES / name).write_text(content, encoding="utf-8")
        print(f"Written tables/{name}", flush=True)


if __name__ == "__main__":
    main()
