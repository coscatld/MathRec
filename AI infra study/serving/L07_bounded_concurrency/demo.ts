import { BoundedExecutor } from './executor.ts';
import { ControlledBackend, ManualClock, flush } from './fakes.ts';
const clock = new ManualClock();
const backend = new ControlledBackend();
const pool = new BoundedExecutor<string>({ concurrency: 1, maxQueue: 1 }, clock);
const a = pool.submit(signal => backend.generate('A', signal), { timeoutMs: 10 });
const b = pool.submit(signal => backend.generate('B', signal), { timeoutMs: 100 });
const c = pool.submit(signal => backend.generate('C', signal), { timeoutMs: 100 });
console.log('C admission:', await c);
console.log('Before timeout:', pool.snapshot());
clock.advance(10);
console.log('A public result:', await a);
console.log('A abort requested:', backend.calls[0].aborted);
console.log('Backend actually active:', backend.active);
console.log('Started IDs:', backend.calls.map(x => x.id));
backend.calls[0].finish('A late result');
await flush();
console.log('After A actually finished, started IDs:', backend.calls.map(x => x.id));
backend.calls[1].finish();
console.log('B public result:', await b);
console.log('Final state:', pool.snapshot(), 'pending timers:', clock.pending);
